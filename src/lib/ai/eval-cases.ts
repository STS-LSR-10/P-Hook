import type { RoutedIntent } from "./intent-router";

/**
 * Sentences as Thai people really type them, with what the bot must do with each. Used by
 * `scripts/eval-router.ts` (the real AI, before a release) and by a unit test that checks the
 * rules offline. More real sentences are welcome: add a row and run the script.
 */
export interface EvalCase {
  text: string;
  /** The group the AI must pick. Left out when only `never` matters. */
  expected?: RoutedIntent;
  /** Groups the AI must never pick (it must not write anything for these). */
  never?: RoutedIntent[];
  /** Words the reminder text must keep. */
  keeps?: string;
  /** money: the baht amount; when the rules are sure of the message they must read this. */
  amount?: number;
}

export const MUTATING: RoutedIntent[] = ["money", "reminder_add", "reminder_edit", "note_add"];

const of = (expected: RoutedIntent, texts: string[]): EvalCase[] =>
  texts.map((text) => ({ text, expected }));
const noWrite = (texts: string[]): EvalCase[] => texts.map((text) => ({ text, never: MUTATING }));
const asks = (texts: string[]): EvalCase[] =>
  texts.map((text) => ({ text, expected: "ask", never: MUTATING }));
const money = (rows: [string, number][]): EvalCase[] =>
  rows.map(([text, amount]) => ({ text, expected: "money", amount }));
const remind = (rows: [string, string?][]): EvalCase[] =>
  rows.map(([text, keeps]) => ({ text, expected: "reminder_add", ...(keeps ? { keeps } : {}) }));

